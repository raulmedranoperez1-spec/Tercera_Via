/*
# News publishing system with deontological review workflow

1. Purpose
- Create a complete editorial workflow for writers (colaborador) to draft, submit, and publish news articles.
- Enforce the 9-article Código Deontológico review before any article can be published.
- Require editor (equipo_editorial) review and signature before publishing.
- Support file uploads (images, documents, audio, video) as media attachments.

2. New tables

## news
The main news article table with full workflow state management.
- id (uuid PK)
- author_id (uuid, defaults to auth.uid(), FK to auth.users) — the writer
- title (text, not null)
- subtitle (text, nullable) — entradilla/subtítulo
- body (text, not null, default '') — full article content in simple markup
- cover_image_url (text, nullable) — main cover image URL
- cover_caption (text, nullable) — pie de foto for cover
- category (text, nullable) — sección/categoría
- tags (text[], default '{}') — etiquetas
- sources (jsonb, default '[]') — array of {label, url} for fuentes documentales
- status (text, not null, default 'borrador') — workflow state
- event_start_at (timestamptz, nullable) — for the 24-hour rule (Artículo 2)
- content_hash (text, nullable) — hash of body+title at last editor approval; if content changes, approval is invalidated
- approved_by (uuid, nullable, FK to auth.users) — editor who approved
- approved_at (timestamptz, nullable) — when editor signed
- approval_version (text, nullable) — the content_hash value at approval time
- editor_notes (text, nullable) — observaciones from editor
- published_at (timestamptz, nullable) — when the article went public
- created_at (timestamptz, default now())
- updated_at (timestamptz, default now())

Valid status values: borrador, pendiente_revision_auto, correcciones_necesarias, pendiente_revision_editor, modificaciones_solicitadas, aprobada, publicada, rechazada, retirada

## news_media
Media files attached to a news article (photos, documents, audio, video).
- id (uuid PK)
- news_id (uuid, FK to news, ON DELETE CASCADE)
- file_path (text, not null) — storage path in the news-media bucket
- file_url (text, not null) — public URL of the file
- file_type (text, not null) — image | document | audio | video
- file_name (text, not null) — original filename
- mime_type (text, not null)
- file_size (integer, not null) — bytes
- caption (text, nullable) — pie de foto
- sort_order (integer, default 0) — ordering for photos
- created_at (timestamptz, default now())

## news_versions
Version history of news content, saved at each editor submission.
- id (uuid PK)
- news_id (uuid, FK to news, ON DELETE CASCADE)
- version_number (integer, not null)
- title (text, not null)
- subtitle (text, nullable)
- body (text, not null)
- content_hash (text, not null)
- created_by (uuid, FK to auth.users)
- created_at (timestamptz, default now())

## news_review_reports
Deontological review reports generated by the automated system.
- id (uuid PK)
- news_id (uuid, FK to news, ON DELETE CASCADE)
- report_text (text, not null) — full AI-generated report
- article_results (jsonb, default '[]') — array of {article_number, status, details}
- passed (boolean, not null) — whether all articles passed
- created_at (timestamptz, default now())

## news_editor_reviews
Editor review and signature records.
- id (uuid PK)
- news_id (uuid, FK to news, ON DELETE CASCADE)
- editor_id (uuid, FK to auth.users)
- result (text, not null) — aprobada | rechazada | modificaciones
- notes (text, nullable) — editor observations
- content_hash (text, not null) — the version reviewed
- created_at (timestamptz, default now())

3. Security — RLS and policies

## news
- Writers (colaborador, equipo_editorial) can CRUD their own news.
- Editors (equipo_editorial) can SELECT all news (to review pending items).
- Anyone (anon, authenticated) can SELECT news with status = 'publicada' (published articles).
- Only the author can INSERT/UPDATE/DELETE their own drafts.
- An editor can UPDATE status fields (approved_by, approved_at, editor_notes) on news they're reviewing — handled via a separate UPDATE policy for equipo_editorial.

## news_media, news_versions, news_review_reports, news_editor_reviews
- Owner (author) can SELECT/INSERT their own.
- Editors can SELECT all (for review).
- Published news media is publicly readable.

4. Storage
- Create a 'news-media' storage bucket (public) for file uploads.
- Policies: authenticated users can upload to their own folder; public can read.

5. Indexes
- news: author_id, status, published_at
- news_media: news_id
- news_versions: news_id, version_number
- news_review_reports: news_id
- news_editor_reviews: news_id

6. Non-destructive
- No existing tables are modified, dropped, or renamed.
- No data is deleted.
- All new tables are created with IF NOT EXISTS.
*/

-- ============================================================
-- news table
-- ============================================================
CREATE TABLE IF NOT EXISTS public.news (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  author_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  title text NOT NULL,
  subtitle text,
  body text NOT NULL DEFAULT '',
  cover_image_url text,
  cover_caption text,
  category text,
  tags text[] NOT NULL DEFAULT '{}',
  sources jsonb NOT NULL DEFAULT '[]'::jsonb,
  status text NOT NULL DEFAULT 'borrador',
  event_start_at timestamptz,
  content_hash text,
  approved_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  approved_at timestamptz,
  approval_version text,
  editor_notes text,
  published_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.news ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS idx_news_author_id ON public.news(author_id);
CREATE INDEX IF NOT EXISTS idx_news_status ON public.news(status);
CREATE INDEX IF NOT EXISTS idx_news_published_at ON public.news(published_at DESC);

-- Helper: is the current user an editor?
-- We check profiles.role = 'equipo_editorial'
-- Used in policies below.

-- Writer can read their own news (any status)
DROP POLICY IF EXISTS "news_select_own" ON public.news;
CREATE POLICY "news_select_own"
ON public.news FOR SELECT
TO authenticated
USING (auth.uid() = author_id);

-- Editors can read all news (for review queue)
DROP POLICY IF EXISTS "news_select_editor" ON public.news;
CREATE POLICY "news_select_editor"
ON public.news FOR SELECT
TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = auth.uid() AND p.role = 'equipo_editorial'
  )
);

-- Published news is publicly readable
DROP POLICY IF EXISTS "news_select_published" ON public.news;
CREATE POLICY "news_select_published"
ON public.news FOR SELECT
TO anon, authenticated
USING (status = 'publicada');

-- Writers can insert their own news
DROP POLICY IF EXISTS "news_insert_own" ON public.news;
CREATE POLICY "news_insert_own"
ON public.news FOR INSERT
TO authenticated
WITH CHECK (auth.uid() = author_id);

-- Writers can update their own news (but not the approval fields)
DROP POLICY IF EXISTS "news_update_own" ON public.news;
CREATE POLICY "news_update_own"
ON public.news FOR UPDATE
TO authenticated
USING (auth.uid() = author_id)
WITH CHECK (auth.uid() = author_id);

-- Editors can update news (to approve/reject/request changes)
DROP POLICY IF EXISTS "news_update_editor" ON public.news;
CREATE POLICY "news_update_editor"
ON public.news FOR UPDATE
TO authenticated
USING (
  EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = auth.uid() AND p.role = 'equipo_editorial'
  )
)
WITH CHECK (
  EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id = auth.uid() AND p.role = 'equipo_editorial'
  )
);

-- Writers can delete their own drafts (not published/approved)
DROP POLICY IF EXISTS "news_delete_own" ON public.news;
CREATE POLICY "news_delete_own"
ON public.news FOR DELETE
TO authenticated
USING (auth.uid() = author_id AND status IN ('borrador', 'correcciones_necesarias', 'rechazada', 'modificaciones_solicitadas'));

-- Grants for news
GRANT SELECT ON public.news TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.news TO authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.news TO service_role;

