-- Storage bucket for news media
-- ============================================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('news-media', 'news-media', true)
ON CONFLICT (id) DO NOTHING;

-- Upload: authenticated users can upload to their own folder
DROP POLICY IF EXISTS "news_media_upload_own" ON storage.objects;
CREATE POLICY "news_media_upload_own"
ON storage.objects FOR INSERT
TO authenticated
WITH CHECK (
  bucket_id = 'news-media'
  AND (storage.foldername(name))[1] = auth.uid()::text
);

-- Public read for news-media bucket
DROP POLICY IF EXISTS "news_media_read_public" ON storage.objects;
CREATE POLICY "news_media_read_public"
ON storage.objects FOR SELECT
TO anon, authenticated
USING (bucket_id = 'news-media');

-- Owner can delete their own files
DROP POLICY IF EXISTS "news_media_delete_own" ON storage.objects;
CREATE POLICY "news_media_delete_own"
ON storage.objects FOR DELETE
TO authenticated
USING (
  bucket_id = 'news-media'
  AND (storage.foldername(name))[1] = auth.uid()::text
);
